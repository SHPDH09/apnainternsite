#!/usr/bin/env node
/**
 * After Vite build: Cloudflare Workers asset upload tweaks.
 *
 * Do NOT put Netlify-style public/_redirects or public/_headers in the repo:
 * Vite copies public/ into dist/, and Vercel merges those files with vercel.json.
 * A /api/* proxy in _redirects conflicts with Vercel /api serverless functions and
 * fails deployment. Routing for both platforms lives in vercel.json (Vercel) and
 * cloudflare/worker.ts (Cloudflare Workers).
 */
import fs from "node:fs";
import path from "node:path";

const distDir = path.resolve("dist");

if (!fs.existsSync(distDir)) {
  console.warn("[postbuild-cloudflare] dist/ missing, skipping");
  process.exit(0);
}

// Strip any legacy routing files that may linger from an old public/ copy.
for (const name of ["_redirects", "_headers"]) {
  const p = path.join(distDir, name);
  if (fs.existsSync(p)) {
    fs.unlinkSync(p);
    console.log(`[postbuild-cloudflare] removed dist/${name}`);
  }
}

const assetsIgnore = `# Generated by scripts/postbuild-cloudflare.mjs
_redirects
_headers
wrangler.toml
`;

fs.writeFileSync(path.join(distDir, ".assetsignore"), assetsIgnore, "utf8");
console.log("[postbuild-cloudflare] wrote dist/.assetsignore");

try {
  const { execSync } = await import("node:child_process");
  execSync("node scripts/cloudflare-sync-mail-secrets.mjs", { stdio: "inherit" });
  const hasCfAuth =
    Boolean(process.env.CLOUDFLARE_API_TOKEN?.trim()) ||
    Boolean(process.env.WRANGLER_API_TOKEN?.trim());
  if (hasCfAuth) {
    execSync("node scripts/wrangler-deploy-ci.mjs", { stdio: "inherit", env: process.env });
  }
} catch (e) {
  console.warn("[postbuild-cloudflare] optional Cloudflare deploy skipped:", e instanceof Error ? e.message : e);
}
