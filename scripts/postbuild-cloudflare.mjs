#!/usr/bin/env node
/**
 * After Vite build: exclude Workers-incompatible files from static asset upload.
 * External URL rules in _redirects only work on Cloudflare Pages, not Workers assets.
 */
import fs from "node:fs";
import path from "node:path";

const distDir = path.resolve("dist");

if (!fs.existsSync(distDir)) {
  console.warn("[postbuild-cloudflare] dist/ missing, skipping");
  process.exit(0);
}

const assetsIgnore = `# Generated by scripts/postbuild-cloudflare.mjs
_redirects
_headers
wrangler.toml
`;

fs.writeFileSync(path.join(distDir, ".assetsignore"), assetsIgnore, "utf8");
console.log("[postbuild-cloudflare] wrote dist/.assetsignore");
