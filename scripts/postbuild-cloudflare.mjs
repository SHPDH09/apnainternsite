#!/usr/bin/env node
/**
 * After Vite build: write dist/wrangler.toml so deploy works even if CI runs
 * wrangler from the build output directory (assets directory = ".").
 */
import fs from "node:fs";
import path from "node:path";

const distDir = path.resolve("dist");
const distWrangler = path.join(distDir, "wrangler.toml");

if (!fs.existsSync(distDir)) {
  console.warn("[postbuild-cloudflare] dist/ missing, skipping");
  process.exit(0);
}

const contents = `# Generated by scripts/postbuild-cloudflare.mjs — do not edit
name = "apnainternsite"
compatibility_date = "2024-09-23"

[assets]
directory = "."
not_found_handling = "single-page-application"
`;

fs.writeFileSync(distWrangler, contents, "utf8");
console.log("[postbuild-cloudflare] wrote dist/wrangler.toml");
